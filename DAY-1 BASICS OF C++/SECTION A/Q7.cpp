// 7. Write a program to input an integer and print the value of:
// • x + 5
// • x - 3
// • x * 2
// • x / 2
// • x % 2

#include <iostream>
using namespace std;
int main()
{
    int x;
    cout << "Enter an integer:";
    cin >> x;
    cout << "The value of " << " x+5: " << x + 5 << endl;
    cout << "The value of " << " x-3: " << x - 3 << endl;
    cout << "The value of " << " x*2: " << x * 2 << endl;
    cout << "The value of " << " x/2: " << x / 2 << endl;
    cout << "The value of " << " x%2: " << x % 2 << endl;
}